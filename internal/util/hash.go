const DefaultReplicas = 150

// HashSlot returns the hash slot (0–16383) for a key, compatible with Redis cluster.
func HashSlot(key string) uint16 {
	// Check for hash tags {tag}
	start := -1
	for i := 0; i < len(key); i++ {
		if key[i] == '{' {
			start = i
		} else if key[i] == '}' && start >= 0 {
			if i > start+1 {
				key = key[start+1 : i]
			}
			break
		}
	}
	return crc16([]byte(key)) % 16384
}

// MurmurHash32 returns a 32-bit Murmur3 hash of key.
func MurmurHash32(key string) uint32 {
	return murmur3.Sum32([]byte(key))
}

// FNVHash64 returns a 64-bit FNV-1a hash of key.
func FNVHash64(key string) uint64 {
	h := fnv.New64a()
	h.Write([]byte(key))
	return h.Sum64()
}

// ShardIndex returns which shard (0..n-1) a key belongs to.
func ShardIndex(key string, numShards int) int {
	if numShards <= 0 {
		return 0
	}
	return int(MurmurHash32(key)) % numShards
}

// UInt64ToBytes converts uint64 to big-endian bytes.
func UInt64ToBytes(v uint64) []byte {
	b := make([]byte, 8)
	binary.BigEndian.PutUint64(b, v)
	return b
}

// BytesToUInt64 converts big-endian bytes to uint64.
func BytesToUInt64(b []byte) uint64 {
	return binary.BigEndian.Uint64(b)
}

